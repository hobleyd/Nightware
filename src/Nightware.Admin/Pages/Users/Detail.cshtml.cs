using Microsoft.AspNetCore.Mvc;

using Nightware.Application.Administration;
using Nightware.Application.Administration.Groups;
using Nightware.Application.Administration.SharedMailboxes;
using Nightware.Application.Administration.Admins;
using Nightware.Application.Administration.Entities;
using Nightware.Application.Administration.Users;
using Nightware.Domain.Administration;
using Nightware.Domain.Kernel;

namespace Nightware.Admin.Pages.Users;

/// <summary>One user: link state per backend and every lifecycle action the actor may take.</summary>
public sealed class DetailModel(
    IAdminActor actor,
    GetUser getUser,
    RepairUser repair,
    ResetUserCredential reset,
    SetUserAliases setAliases,
    SetUserProfile setProfile,
    VerifyUserEmail verifyEmail,
    OffboardUser offboard,
    ReinstateUser reinstate,
    SetGlobalAdmin setGlobalAdmin,
    ListEntities entities,
    ListUserGroups userGroups,
    ListUserSharedMailboxes userMailboxes,
    AdministrationOptions options) : ConsolePageModel(actor)
{
    [BindProperty(SupportsGet = true)]
    public string Id { get; set; } = string.Empty;

    public UserDetail Subject { get; private set; } = null!;

    /// <summary>The name of the user's entity, for the breadcrumb; null when it cannot be read.</summary>
    public string? EntityName { get; private set; }

    /// <summary>The groups the user is in, in entities the actor manages; null when they could not be read (a view only).</summary>
    public IReadOnlyList<Group>? Groups { get; private set; }

    /// <summary>The shared mailboxes the user may open, in entities the actor manages; null when they could not be read.</summary>
    public IReadOnlyList<SharedMailbox>? Mailboxes { get; private set; }

    /// <summary>A temporary password generated by this request, shown once.</summary>
    public TemporaryCredential? Credential { get; private set; }

    public bool MayDeleteData => Actor.IsGlobal || (options.EntityAdminsMayDeleteData && Actor.MayManage(Subject.User.EntityId));

    public Task<IActionResult> OnGetAsync(CancellationToken cancellationToken) => RenderAsync(cancellationToken);

    public async Task<IActionResult> OnPostRepairAsync(CancellationToken cancellationToken) =>
        await AfterAsync(await repair.ExecuteAsync(Id, cancellationToken), "Repair finished.", cancellationToken);

    public async Task<IActionResult> OnPostVerifyEmailAsync(CancellationToken cancellationToken) =>
        await AfterAsync(await verifyEmail.ExecuteAsync(Id, cancellationToken), "Email marked verified.", cancellationToken);

    public async Task<IActionResult> OnPostResetAsync(CredentialDelivery delivery, CancellationToken cancellationToken)
    {
        Result<TemporaryCredential?> issued = await reset.ExecuteAsync(Id, delivery, cancellationToken);
        if (!issued.IsSuccess)
        {
            return Fail(issued.Error) ?? await RenderAsync(cancellationToken);
        }

        if (issued.Value is null)
        {
            Notice = "A set-password link was e-mailed to them.";
            return RedirectToPage(new { id = Id });
        }

        // Rendered, not redirected, so the password exists on this one no-store response only.
        Credential = issued.Value;
        return await RenderAsync(cancellationToken);
    }

    public async Task<IActionResult> OnPostAliasesAsync(string? aliases, CancellationToken cancellationToken) =>
        await AfterAsync(
            await setAliases.ExecuteAsync(Id, (aliases ?? string.Empty).Split([',', ';', '\n', ' '], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries), cancellationToken),
            "Aliases saved.",
            cancellationToken);

    public async Task<IActionResult> OnPostProfileAsync(
        string? jobTitle, string? department, string? companyName, string? officeLocation, string? businessPhones, string? mobilePhone, CancellationToken cancellationToken) =>
        await AfterAsync(
            await setProfile.ExecuteAsync(
                Id,
                new UserProfile
                {
                    JobTitle = jobTitle,
                    Department = department,
                    CompanyName = companyName,
                    OfficeLocation = officeLocation,
                    BusinessPhones = (businessPhones ?? string.Empty).Split([',', ';', '\n'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries),
                    MobilePhone = mobilePhone,
                },
                cancellationToken),
            "Profile saved.",
            cancellationToken);

    public async Task<IActionResult> OnPostOffboardAsync(bool confirm, CancellationToken cancellationToken)
    {
        if (!confirm)
        {
            ModelState.AddModelError(string.Empty, "Tick the box to confirm the offboarding.");
            return await RenderAsync(cancellationToken);
        }

        Result<UserDetail> offboarded = await offboard.ExecuteAsync(Id, cancellationToken);
        return await AfterAsync(offboarded, offboarded.IsSuccess ? OffboardingNotice.For(offboarded.Value, options.AccessTokenLifespan) : string.Empty, cancellationToken);
    }

    public async Task<IActionResult> OnPostReinstateAsync(bool recreateMailbox, bool confirm, CancellationToken cancellationToken)
    {
        if (!confirm)
        {
            ModelState.AddModelError(string.Empty, "Tick the box to confirm the reinstatement.");
            return await RenderAsync(cancellationToken);
        }

        return await AfterAsync(await reinstate.ExecuteAsync(Id, recreateMailbox, cancellationToken), "Reinstated: they can sign in again in every system.", cancellationToken);
    }

    public async Task<IActionResult> OnPostGlobalAdminAsync(bool grant, bool confirm, CancellationToken cancellationToken)
    {
        if (!confirm)
        {
            ModelState.AddModelError(string.Empty, "Tick the box to confirm the global administrator rights.");
            return await RenderAsync(cancellationToken);
        }

        Result result = await setGlobalAdmin.ExecuteAsync(Id, grant, cancellationToken);
        return await AfterAsync(result.IsSuccess ? Result<bool>.Success(true) : result.Error, grant ? "Global administrator rights granted." : "Global administrator rights removed.", cancellationToken);
    }

    private async Task<IActionResult> AfterAsync<T>(Result<T> result, string notice, CancellationToken cancellationToken)
    {
        if (result.IsSuccess)
        {
            Notice = notice;
            return RedirectToPage(new { id = Id });
        }

        return Fail(result.Error) ?? await RenderAsync(cancellationToken);
    }

    private async Task<IActionResult> RenderAsync(CancellationToken cancellationToken)
    {
        if (!TryGet(await getUser.ExecuteAsync(Id, cancellationToken), out UserDetail user, out IActionResult? failure))
        {
            return failure!;
        }

        Subject = user;
        Result<IReadOnlyList<Entity>> manageable = await entities.ExecuteAsync(cancellationToken);
        EntityName = manageable.IsSuccess ? manageable.Value.FirstOrDefault(e => e.Id == user.User.EntityId)?.Name : null;
        Result<IReadOnlyList<Group>> groups = user.OffLimits is null ? await userGroups.ExecuteAsync(Id, cancellationToken) : Error.Forbidden("off limits");
        Groups = groups.IsSuccess ? groups.Value : null;
        Result<IReadOnlyList<SharedMailbox>> mailboxes = user.OffLimits is null ? await userMailboxes.ExecuteAsync(Id, cancellationToken) : Error.Forbidden("off limits");
        Mailboxes = mailboxes.IsSuccess ? mailboxes.Value : null;
        return Page();
    }
}
