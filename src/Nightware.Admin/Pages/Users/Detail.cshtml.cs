using Microsoft.AspNetCore.Mvc;

using Nightware.Application.Administration;
using Nightware.Application.Administration.Admins;
using Nightware.Application.Administration.Users;
using Nightware.Domain.Administration;
using Nightware.Domain.Kernel;

namespace Nightware.Admin.Pages.Users;

/// <summary>One user: link state per backend and every lifecycle action the actor may take.</summary>
public sealed class DetailModel(
    IAdminActor actor,
    GetUser getUser,
    RepairUser repair,
    ResetUserCredential reset,
    SetUserAliases setAliases,
    OffboardUser offboard,
    ReinstateUser reinstate,
    SetGlobalAdmin setGlobalAdmin,
    AdministrationOptions options) : ConsolePageModel(actor)
{
    [BindProperty(SupportsGet = true)]
    public string Id { get; set; } = string.Empty;

    public UserDetail Subject { get; private set; } = null!;

    /// <summary>A temporary password generated by this request, shown once.</summary>
    public TemporaryCredential? Credential { get; private set; }

    public bool MayDeleteData => Actor.IsGlobal || (options.EntityAdminsMayDeleteData && Actor.MayManage(Subject.User.EntityId));

    public Task<IActionResult> OnGetAsync(CancellationToken cancellationToken) => RenderAsync(cancellationToken);

    public async Task<IActionResult> OnPostRepairAsync(CancellationToken cancellationToken) =>
        await AfterAsync(await repair.ExecuteAsync(Id, cancellationToken), "Repair finished.", cancellationToken);

    public async Task<IActionResult> OnPostResetAsync(CredentialDelivery delivery, CancellationToken cancellationToken)
    {
        Result<TemporaryCredential?> issued = await reset.ExecuteAsync(Id, delivery, cancellationToken);
        if (!issued.IsSuccess)
        {
            return Fail(issued.Error) ?? await RenderAsync(cancellationToken);
        }

        if (issued.Value is null)
        {
            Notice = "Keycloak has e-mailed a set-password link.";
            return RedirectToPage(new { id = Id });
        }

        // Rendered, not redirected, so the password exists on this one no-store response only.
        Credential = issued.Value;
        return await RenderAsync(cancellationToken);
    }

    public async Task<IActionResult> OnPostAliasesAsync(string? aliases, CancellationToken cancellationToken) =>
        await AfterAsync(
            await setAliases.ExecuteAsync(Id, (aliases ?? string.Empty).Split([',', ';', '\n', ' '], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries), cancellationToken),
            "Aliases saved.",
            cancellationToken);

    public async Task<IActionResult> OnPostOffboardAsync(bool confirm, CancellationToken cancellationToken)
    {
        if (!confirm)
        {
            ModelState.AddModelError(string.Empty, "Tick the box to confirm the offboarding.");
            return await RenderAsync(cancellationToken);
        }

        return await AfterAsync(await offboard.ExecuteAsync(Id, cancellationToken), "Offboarded: sign-in is disabled and sessions ended. Mail and files are kept.", cancellationToken);
    }

    public async Task<IActionResult> OnPostReinstateAsync(bool recreateMailbox, CancellationToken cancellationToken) =>
        await AfterAsync(await reinstate.ExecuteAsync(Id, recreateMailbox, cancellationToken), "Reinstated.", cancellationToken);

    public async Task<IActionResult> OnPostGlobalAdminAsync(bool grant, CancellationToken cancellationToken)
    {
        Result result = await setGlobalAdmin.ExecuteAsync(Id, grant, cancellationToken);
        return await AfterAsync(result.IsSuccess ? Result<bool>.Success(true) : result.Error, grant ? "Global administrator rights granted." : "Global administrator rights removed.", cancellationToken);
    }

    private async Task<IActionResult> AfterAsync<T>(Result<T> result, string notice, CancellationToken cancellationToken)
    {
        if (result.IsSuccess)
        {
            Notice = notice;
            return RedirectToPage(new { id = Id });
        }

        return Fail(result.Error) ?? await RenderAsync(cancellationToken);
    }

    private async Task<IActionResult> RenderAsync(CancellationToken cancellationToken)
    {
        if (!TryGet(await getUser.ExecuteAsync(Id, cancellationToken), out UserDetail user, out IActionResult? failure))
        {
            return failure!;
        }

        Subject = user;
        return Page();
    }
}
