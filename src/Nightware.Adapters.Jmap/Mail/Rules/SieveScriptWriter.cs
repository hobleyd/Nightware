using System.Globalization;
using System.Text;
using Nightware.Adapters.Jmap.Mail.Read;
using Nightware.Application.Common.Time;
using Nightware.Domain.Calendar;
using Nightware.Domain.Kernel;
using Nightware.Domain.Mail;
using Nightware.Domain.MailboxSettings;

namespace Nightware.Adapters.Jmap.Mail.Rules;

/// <summary>
/// Writes Nightware's Sieve script (ADR 0006 D5): the automatic reply first, in the shape of Stalwart's own
/// <c>VacationResponse</c> script so replies behave as before, then each enabled rule in sequence order. A reply
/// whose internal and external parts differ tests the envelope sender's domain (where the reply goes) against the entity's
/// (<see cref="FilterState.InternalDomains"/>): those get the internal message, everyone else the external one when
/// the audience is <c>all</c> and nothing otherwise (<c>contactsOnly</c> too: contacts live in Nextcloud, out of
/// Sieve's reach, so the safe reading is "no strangers").
/// Client text only ever appears inside quoted strings (escaped) or a dot-stuffed <c>text:</c> block.
/// </summary>
internal static class SieveScriptWriter
{
    public const string ScriptName = "nightware-rules";

    private static readonly string[] Extensions = ["body", "copy", "date", "envelope", "fileinto", "imap4flags", "mailboxid", "mime", "relational", "vacation"];

    /// <param name="trashId">The Deleted Items mailbox, for <c>delete</c> actions.</param>
    public static string Write(FilterState state, string? trashId)
    {
        ArgumentNullException.ThrowIfNull(state);
        var script = new StringBuilder();
        script.Append("require ").Append(List(Extensions)).Append(";\n");
        script.Append("# ").Append(ScriptName).Append(": generated by Nightware; edits are overwritten.\n");
        script.Append(state.ToComment()).Append('\n');
        if (state.AutoReply is { Status: not AutoReplyStatus.Disabled } reply)
        {
            WriteVacation(script, reply, state.InternalDomains);
        }

        foreach (var rule in state.Rules.Where(static r => r.IsEnabled).OrderBy(static r => r.Sequence))
        {
            WriteRule(script, rule, trashId);
        }

        return script.ToString();
    }

    /// <summary>True when one reply to everyone can't express <paramref name="reply"/>.</summary>
    public static bool Splits(AutoReplySetting reply)
    {
        ArgumentNullException.ThrowIfNull(reply);
        return reply.Status != AutoReplyStatus.Disabled
            && (reply.ExternalAudience != ExternalAudience.All || !string.Equals(InternalMessage(reply), ExternalMessage(reply), StringComparison.Ordinal));
    }

    /// <summary>The internal message, or the external one when it has none (Graph keeps both; one may be blank).</summary>
    public static string InternalMessage(AutoReplySetting reply) =>
        (string.IsNullOrEmpty(reply.InternalReplyMessage) ? reply.ExternalReplyMessage : reply.InternalReplyMessage) ?? string.Empty;

    public static string ExternalMessage(AutoReplySetting reply) =>
        (string.IsNullOrEmpty(reply.ExternalReplyMessage) ? reply.InternalReplyMessage : reply.ExternalReplyMessage) ?? string.Empty;

    private static void WriteVacation(StringBuilder script, AutoReplySetting reply, IReadOnlyList<string> internalDomains)
    {
        var opened = 0;
        if (reply.Status == AutoReplyStatus.Scheduled)
        {
            foreach (var (comparison, bound) in new[] { ("ge", reply.ScheduledStartDateTime), ("le", reply.ScheduledEndDateTime) })
            {
                if (bound is not null)
                {
                    script.Append("if currentdate :value \"").Append(comparison).Append("\" \"iso8601\" \"").Append(Utc(bound)).Append("\" {\n");
                    opened++;
                }
            }
        }

        if (!Splits(reply) || internalDomains.Count == 0)
        {
            WriteVacationAction(script, ExternalMessage(reply));
        }
        else
        {
            // The envelope sender, not the From header: vacation replies to the envelope sender (RFC 5230 §4.4), so a
            // forged From can't steer the internal message to a stranger.
            script.Append("if envelope :domain :is \"from\" ").Append(List(internalDomains)).Append(" {\n");
            WriteVacationAction(script, InternalMessage(reply));
            script.Append('}');
            if (reply.ExternalAudience == ExternalAudience.All)
            {
                script.Append(" else {\n");
                WriteVacationAction(script, ExternalMessage(reply));
                script.Append('}');
            }

            script.Append('\n');
        }

        script.Append('}', opened);
        if (opened > 0)
        {
            script.Append('\n');
        }
    }

    private static void WriteVacationAction(StringBuilder script, string html)
    {
        var boundary = "nightware-" + Guid.NewGuid().ToString("N");
        var body = new StringBuilder()
            .Append("Content-Type: multipart/alternative;\n boundary=\"").Append(boundary).Append("\"\n\n")
            .Append("--").Append(boundary).Append("\nContent-Type: text/plain; charset=\"utf-8\"\nContent-Transfer-Encoding: 8bit\n\n")
            .Append(HtmlToText.Convert(html)).Append('\n')
            .Append("--").Append(boundary).Append("\nContent-Type: text/html; charset=\"utf-8\"\nContent-Transfer-Encoding: 8bit\n\n")
            .Append(html).Append('\n')
            .Append("--").Append(boundary).Append("--\n");
        script.Append("vacation :mime ").Append(Text(body.ToString())).Append(";\n");
    }

    private static void WriteRule(StringBuilder script, MessageRule rule, string? trashId)
    {
        var tests = Tests(rule.Conditions);
        var exceptions = Tests(rule.Exceptions);
        if (exceptions.Count > 0)
        {
            tests.Add("not anyof(" + string.Join(", ", exceptions) + ")");
        }

        script.Append("# rule ").Append(Quoted(rule.DisplayName)).Append('\n');
        script.Append("if ").Append(tests.Count switch { 0 => "true", 1 => tests[0], _ => "allof(" + string.Join(", ", tests) + ")" }).Append(" {\n");
        var actions = rule.Actions;
        if (actions.MarkAsRead)
        {
            script.Append("  addflag \"\\\\Seen\";\n");
        }

        foreach (var forward in actions.ForwardTo)
        {
            script.Append("  redirect :copy ").Append(Quoted(forward.Address)).Append(";\n");
        }

        foreach (var redirect in actions.RedirectTo)
        {
            script.Append("  redirect ").Append(Quoted(redirect.Address)).Append(";\n");
        }

        if (actions.CopyToFolder is { } copy)
        {
            script.Append("  fileinto :copy :mailboxid ").Append(Quoted(copy.Value)).Append(" \"INBOX\";\n");
        }

        if (actions.PermanentDelete)
        {
            script.Append("  discard;\n");
        }
        else if (actions.Delete && trashId is not null)
        {
            script.Append("  fileinto :mailboxid ").Append(Quoted(trashId)).Append(" \"INBOX\";\n");
        }
        else if (actions.MoveToFolder is { } move)
        {
            script.Append("  fileinto :mailboxid ").Append(Quoted(move.Value)).Append(" \"INBOX\";\n");
        }

        if (actions.StopProcessingRules)
        {
            script.Append("  stop;\n");
        }

        script.Append("}\n");
    }

    private static List<string> Tests(MessageRulePredicates p)
    {
        var tests = new List<string>();
        if (p.SubjectContains.Count > 0)
        {
            tests.Add("header :contains \"subject\" " + List(p.SubjectContains));
        }

        if (p.BodyContains.Count > 0)
        {
            tests.Add("body :text :contains " + List(p.BodyContains));
        }

        if (p.BodyOrSubjectContains.Count > 0)
        {
            tests.Add($"anyof(header :contains \"subject\" {List(p.BodyOrSubjectContains)}, body :text :contains {List(p.BodyOrSubjectContains)})");
        }

        if (p.SenderContains.Count > 0)
        {
            tests.Add("header :contains \"from\" " + List(p.SenderContains));
        }

        if (p.RecipientContains.Count > 0)
        {
            tests.Add("header :contains [\"to\", \"cc\"] " + List(p.RecipientContains));
        }

        if (p.FromAddresses.Count > 0)
        {
            tests.Add("address :is \"from\" " + List(p.FromAddresses.Select(static a => a.Address)));
        }

        if (p.SentToAddresses.Count > 0)
        {
            tests.Add("address :is [\"to\", \"cc\"] " + List(p.SentToAddresses.Select(static a => a.Address)));
        }

        if (p.HasAttachments is { } has)
        {
            const string attachment = "header :mime :anychild :contains \"Content-Disposition\" \"attachment\"";
            tests.Add(has ? attachment : "not " + attachment);
        }

        if (p.Importance is { } importance)
        {
            const string high = "anyof(header :is \"importance\" \"high\", header :matches \"x-priority\" [\"1*\", \"2*\"])";
            const string low = "anyof(header :is \"importance\" \"low\", header :matches \"x-priority\" [\"4*\", \"5*\"])";
            tests.Add(importance switch
            {
                Importance.High => high,
                Importance.Low => low,
                _ => $"not anyof({high}, {low})",
            });
        }

        return tests;
    }

    private static string List(IEnumerable<string> values) => "[" + string.Join(", ", values.Select(Quoted)) + "]";

    /// <summary>A Sieve quoted string (RFC 5228 §2.4.2): backslash and quote escaped; line breaks cannot occur in a header test.</summary>
    internal static string Quoted(string value) =>
        "\"" + value.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal)
            .Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    /// <summary>A Sieve multi-line string (RFC 5228 §2.4.2): lines starting with a dot get another.</summary>
    internal static string Text(string value)
    {
        var lines = value.ReplaceLineEndings("\n").Split('\n').Select(static l => l.StartsWith('.') ? "." + l : l);
        return "text:\n" + string.Join("\n", lines).TrimEnd('\n') + "\n.\n";
    }

    private static string Utc(DateTimeTimeZone value) =>
        GraphTimeZone.ToInstant(value.DateTime, value.TimeZone).UtcDateTime.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture);
}
